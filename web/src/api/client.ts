import createClient from 'openapi-fetch'
import { isSavingRequest, notifySaved } from '../savedSignal'
import type { components, paths } from './schema'

/** Typisierter Client, erzeugt aus dem OpenAPI-Dokument der API (npm run gen:api). */
export const api = createClient<paths>({
  baseUrl: window.location.origin,
  credentials: 'same-origin',
  // fetch erst beim Aufruf auflösen, damit Tests es ersetzen können.
  fetch: (request) => globalThis.fetch(request),
})

// Jede erfolgreiche Änderung meldet „gespeichert“ (savedSignal.ts): die KI-Leiste bietet danach an, die Frage zu wiederholen.
api.use({
  onResponse({ request, response }) {
    if (response.ok && isSavingRequest(request.method, request.url)) notifySaved()
  },
})

